/**
 * ClearTrace — test-evidence-upload.js
 * End-to-end smoke test for the BRSR evidence vault endpoints.
 *
 * Steps:
 *   1. Login as demo admin to get a bearer token
 *   2. Resolve the demo company's BRSR submission ID (FY 2024-25)
 *   3. Upload a small test file to POST /api/brsr/evidence/:id/test-field
 *   4. Log the vault row returned
 *   5. GET /api/brsr/evidence/:id and log the signed URL for the uploaded file
 *
 * Usage:  node scripts/test-evidence-upload.js
 * Requires the local server to be running on PORT (default 3001).
 */

'use strict';

require('dotenv').config();

const fs   = require('fs');
const path = require('path');

const BASE_URL  = `http://localhost:${process.env.PORT || 3001}`;
const DEMO_EMAIL    = 'admin@verdantgroup.com';
const DEMO_PASSWORD = 'Demo1234!';
const FIELD_REF     = 'test-field';
const TEST_FILE_PATH = path.join(__dirname, 'test-evidence-dummy.pdf');

// ── Create dummy 1 KB test file if it doesn't already exist ──────────────────
if (!fs.existsSync(TEST_FILE_PATH)) {
  // Minimal valid-looking PDF header so the extension and mime type are consistent
  const content = '%PDF-1.4\n' +
    '% ClearTrace BRSR evidence vault — dummy test file\n' +
    '% Auto-generated by test-evidence-upload.js\n' +
    'x'.repeat(1024 - 95); // pad to ~1 KB
  fs.writeFileSync(TEST_FILE_PATH, content, 'utf8');
  console.log(`✓ Created dummy test file: ${TEST_FILE_PATH} (${fs.statSync(TEST_FILE_PATH).size} bytes)\n`);
} else {
  console.log(`✓ Using existing test file: ${TEST_FILE_PATH} (${fs.statSync(TEST_FILE_PATH).size} bytes)\n`);
}

// ── Helper: pretty-print a response ──────────────────────────────────────────
async function logResponse(label, res) {
  let body;
  const ct = res.headers.get('content-type') || '';
  if (ct.includes('application/json')) {
    body = await res.json();
    console.log(`── ${label} [HTTP ${res.status}] ──`);
    console.log(JSON.stringify(body, null, 2));
  } else {
    body = await res.text();
    console.log(`── ${label} [HTTP ${res.status}] ──`);
    console.log(body);
  }
  console.log('');
  return body;
}

// ── Supabase preflight ────────────────────────────────────────────────────────
async function checkSupabase() {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_KEY;
  if (!url || !key || url.includes('your-project')) {
    console.error('✗ SUPABASE_URL / SUPABASE_SERVICE_KEY not configured in .env');
    process.exit(1);
  }
  const res = await fetch(`${url}/storage/v1/bucket`, {
    headers: { Authorization: `Bearer ${key}`, apikey: key }
  });
  if (res.status === 403) {
    const body = await res.text();
    if (body.includes('allowlist')) {
      console.error(`✗ Supabase returned 403 — Host not in allowlist.`);
      console.error(`  The Supabase project has an API allowlist configured.`);
      console.error(`  To fix: Supabase Dashboard → Settings → API → Allowed API hosts`);
      console.error(`  Add this container's egress IP, or set the list to allow all (*).`);
    } else {
      console.error(`✗ Supabase Storage 403: ${body}`);
    }
    process.exit(1);
  }
  if (!res.ok) {
    console.error(`✗ Supabase Storage check failed [${res.status}]: ${await res.text()}`);
    process.exit(1);
  }
  const buckets = await res.json();
  const hasBucket = buckets.some(b => b.name === 'brsr-evidence');
  if (!hasBucket) {
    console.warn(`⚠ Bucket 'brsr-evidence' not found in Supabase Storage.`);
    console.warn(`  Create it: Supabase Dashboard → Storage → New Bucket → brsr-evidence (private)`);
    console.warn(`  Or via CLI: supabase storage buckets create brsr-evidence --private\n`);
  } else {
    console.log(`✓ Supabase reachable. Bucket 'brsr-evidence' exists.\n`);
  }
}

// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  await checkSupabase();

  // ── Step 1: Login ────────────────────────────────────────────────────────────
  console.log(`\n[1] POST ${BASE_URL}/api/auth/login`);
  const loginRes = await fetch(`${BASE_URL}/api/auth/login`, {
    method:  'POST',
    headers: { 'Content-Type': 'application/json' },
    body:    JSON.stringify({ email: DEMO_EMAIL, password: DEMO_PASSWORD }),
  });

  const loginData = await logResponse('Login', loginRes);
  if (!loginRes.ok) {
    console.error('Login failed — is the server running and the demo seed applied?');
    process.exit(1);
  }
  const token = loginData.token;
  console.log(`Bearer token acquired (first 40 chars): ${token.slice(0, 40)}…\n`);

  const headers = { Authorization: `Bearer ${token}` };

  // ── Step 2: Resolve BRSR submission ID for FY 2024-25 ────────────────────────
  console.log(`[2] GET ${BASE_URL}/api/brsr/submission?fy=2024-25`);
  const subRes = await fetch(`${BASE_URL}/api/brsr/submission?fy=2024-25`, { headers });
  const subData = await logResponse('BRSR submission', subRes);

  if (!subRes.ok) {
    console.error('Could not resolve submission — aborting.');
    process.exit(1);
  }
  const submissionId = subData.submission.id;
  console.log(`Submission ID: ${submissionId}  status: ${subData.submission.status}\n`);

  // ── Step 3: Upload the test file ──────────────────────────────────────────────
  const uploadUrl = `${BASE_URL}/api/brsr/evidence/${submissionId}/${FIELD_REF}`;
  console.log(`[3] POST ${uploadUrl}`);

  const formData = new FormData();
  const fileBuffer = fs.readFileSync(TEST_FILE_PATH);
  const blob = new Blob([fileBuffer], { type: 'application/pdf' });
  formData.append('file', blob, path.basename(TEST_FILE_PATH));

  const uploadRes = await fetch(uploadUrl, { method: 'POST', headers, body: formData });
  const uploadData = await logResponse('Upload evidence', uploadRes);

  if (!uploadRes.ok) {
    console.error('Upload failed — check server logs.');
    process.exit(1);
  }
  console.log(`File stored at Supabase path: ${uploadData.file_url}\n`);

  // ── Step 4: GET evidence list and log signed URL ──────────────────────────────
  const listUrl = `${BASE_URL}/api/brsr/evidence/${submissionId}`;
  console.log(`[4] GET ${listUrl}`);
  const listRes = await fetch(listUrl, { headers });
  const listData = await logResponse('Evidence list (grouped by field_ref)', listRes);

  const fieldItems = listData[FIELD_REF] || [];
  if (!fieldItems.length) {
    console.warn(`No items found under field_ref "${FIELD_REF}" — unexpected.`);
  } else {
    console.log(`Signed URL for "${FIELD_REF}" (60-min expiry):`);
    fieldItems.forEach((item, i) => {
      console.log(`  [${i}] ${item.file_name}  (${item.file_size_bytes} bytes)`);
      console.log(`       ${item.signed_url || '(no signed URL)'}`);
    });
  }

  console.log('\n✓ Test complete.\n');
}

main().catch(err => {
  console.error('\nUnhandled error:', err.message);
  process.exit(1);
});
